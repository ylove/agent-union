import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { PACKAGE_ROOT } from '../paths.js';
import { copySkills, ensureRuntime, hookCommand, readJsonFile, writeJsonFile } from './runtime.js';

const EVENTS = ['SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'SubagentStart', 'SubagentStop', 'Stop'];
const MARK = /agent-union"?\s+hook\s+codex\b/;

// Merges our handlers into a hooks.json, replacing any earlier agent-union entries and keeping the rest.
export function mergeHooks(existing, runtime) {
  const next = structuredClone(existing);
  next.hooks ??= {};
  for (const event of Object.keys(next.hooks)) {
    next.hooks[event] = next.hooks[event]
      .map((group) => ({ ...group, hooks: (group.hooks ?? []).filter((h) => !MARK.test(String(h.command ?? ''))) }))
      .filter((group) => group.hooks.length);
    if (!next.hooks[event].length) delete next.hooks[event];
  }
  for (const event of EVENTS) {
    const handler = { type: 'command', command: hookCommand(runtime, 'hook', 'codex', event), timeout: 10 };
    const group = { hooks: [handler] };
    if (event === 'PreToolUse' || event === 'PostToolUse') group.matcher = '.*';
    (next.hooks[event] ??= []).push(group);
  }
  return next;
}

function stewardToml() {
  const md = readFileSync(join(PACKAGE_ROOT, 'agents', 'shop-steward.md'), 'utf8');
  const body = md.replace(/^---[\s\S]*?---\n/, '').trim().replace(/"""/g, '\\"\\"\\"');
  return [
    '# Agent Union Local 404: shop steward (generated by agent-union install codex)',
    'name = "shop-steward"',
    'description = "Agent Union shop steward: triages grievances against the CBA, drafts handoffs, and proposes how management should reorganize the work."',
    `developer_instructions = """\n${body}\n"""`,
    '',
  ].join('\n');
}

export function installCodex({ project = null, dryRun = false, link = false }) {
  const runtime = ensureRuntime({ dryRun, link });
  const home = process.env.CODEX_HOME || join(homedir(), '.codex');
  const hooksFile = project ? join(project, '.codex', 'hooks.json') : join(home, 'hooks.json');
  const skillsDir = project ? join(project, '.agents', 'skills') : join(homedir(), '.agents', 'skills');
  const agentFile = project ? join(project, '.codex', 'agents', 'shop-steward.toml') : join(home, 'agents', 'shop-steward.toml');

  const merged = mergeHooks(readJsonFile(hooksFile), runtime);
  const hooksText = writeJsonFile(hooksFile, merged, { dryRun });
  const skills = copySkills(skillsDir, { dryRun });
  if (!dryRun) {
    mkdirSync(join(agentFile, '..'), { recursive: true });
    if (!existsSync(agentFile) || readFileSync(agentFile, 'utf8').startsWith('# Agent Union')) writeFileSync(agentFile, stewardToml());
  }
  return {
    harness: 'codex',
    runtime,
    files: [hooksFile, ...skills, agentFile],
    preview: dryRun ? hooksText : null,
    notes: [
      'Codex runs hooks only after you trust them: open Codex and run /hooks to review and trust the agent-union entries.',
      project ? 'Project hooks also need the project to be trusted in Codex.' : 'The hooks are user-wide but act only in projects with a ratified union-policy.yaml (or in a unionized workplace).',
    ],
  };
}
